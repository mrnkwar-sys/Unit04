package boletin01;

public class A2Persona {
	String dni;
	String name;
	String surname;
	int age;
	String adult;
	
	A2Persona (String dni, String name, String surname, int age, String adult){
		this.dni = dni;
		this.name = name;
		this.surname = surname;
		this.age = age;
		this.adult = adult;
	}
}
