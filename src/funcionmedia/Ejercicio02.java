package funcionmedia;

public class Ejercicio02 {
	
	public static double media(int firstNumber, int secondNumber) {
		//The average of the numbers introduced
		double average;
		
		average = (double) (firstNumber + secondNumber)/2;
		
		return average;
	}

	public static double media(int firstNumber, int secondNumber, int thirdNumber) {
		//The average of the numbers introduced
		double average;
		
		average = (double) (firstNumber + secondNumber + thirdNumber)/3;
		
		return average;
	}
}
