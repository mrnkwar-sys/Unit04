package funcionsuma;

public class Ejercicio01 {
	
	public static int suma(int firstNumber, int secondNumber) {
		//The result of summoning both numbers
		int result;
		
		result = firstNumber + secondNumber;
		
		return result;
	}
	
	public static double suma(double firstNumber, double secondNumber) {
		//The result of summoning both numbers
		double result;
		
		result = (double) firstNumber + secondNumber;
		
		return result;
	}
}
